#!/usr/bin/env bash
# Build the course website into ./site:
#   - site/index.html is the presenter (slides, live sketches, classroom tools) from ./present
#   - the lesson plans and resources are rendered from Markdown with pandoc
# Usage:  ./build-site.sh      then open site/index.html (works straight from the file system)
set -euo pipefail
cd "$(dirname "$0")"
rm -rf site && mkdir -p site/modules site/resources site/sketches
# plain pages (for printing or without JavaScript), in the presenter's colours and fonts
cat > site/style.css <<'CSS'
@import url("vendor/fonts/fonts.css");
:root{--bg:#FFFBF3;--fg:#23303D;--muted:#5E6B78;--accent:#2D46C9;--green:#57B96A;--deep:#2B7F43;--code:#E4E9FF;--line:#E6E9EE}
body{background:var(--bg);color:var(--fg);font:17px/1.65 Nunito,system-ui,sans-serif;max-width:52rem;margin:0 auto;padding:1rem 16px 4rem}
nav{display:flex;flex-wrap:wrap;gap:6px 16px;padding:.7rem 0;border-bottom:3px dashed var(--line);margin-bottom:1.5rem;font-weight:800;font-size:.95rem}
nav a:first-child{background:var(--green);color:#fff;padding:0 12px;border-radius:999px;text-decoration:none}
a{color:var(--accent)}
h1,h2,h3{font-family:Fredoka,Nunito,sans-serif;font-weight:600;line-height:1.2}
h1{color:var(--deep);font-size:2.4rem}
h2{color:var(--deep)}
code,pre{font-family:'JetBrains Mono',monospace;font-variant-ligatures:none}
pre{background:#1E2740;color:#DCE3F2;padding:.8rem 1rem;border-radius:14px;overflow-x:auto;font-size:.9rem}
code{background:var(--code);color:var(--accent);padding:.1em .3em;border-radius:6px;font-size:.9em}
pre code{background:none;color:inherit;padding:0}
table{border-collapse:separate;border-spacing:0;display:block;overflow-x:auto}
th,td{border-bottom:1px solid var(--line);padding:.45rem .7rem;text-align:left;vertical-align:top}
th{background:var(--green);color:#fff;font-family:Fredoka,sans-serif;font-weight:600}
ul.task-list{list-style:none;padding-left:.5rem}
img{max-width:100%;height:auto;border-radius:14px}
td img{display:block;margin-bottom:.4rem}
@media print{nav{display:none}body{background:#fff}pre{background:#fff;color:#000;border:1px solid #999}}
CSS
render(){ # $1 = source md, $2 = output html, $3 = css path prefix, $4 = home prefix
  pandoc "$1" -f gfm -t html5 -s --syntax-highlighting=none --metadata pagetitle="$(grep -m1 '^# ' "$1" | sed 's/^# //; s/`//g')" \
    -c "$3style.css" --include-before-body=<(printf '<nav><a href="%sindex.html#/notes">Open in the presenter</a><a href="%soverview.html">Overview</a><a href="%sTEACHER-GUIDE.html">Teacher guide</a><a href="%sresources/cheatsheet.html">Cheat sheet</a><a href="%sresources/error-decoder.html">Errors</a><a href="%sresources/book-map.html">Book map</a></nav>' "$4" "$4" "$4" "$4" "$4" "$4") \
    -o "$2"
}
# keep the nav links in step with the printf above (one prefix per link)
render README.md site/overview.html "" ""
render TEACHER-GUIDE.md site/TEACHER-GUIDE.html "" ""
for f in modules/*.md;   do render "$f" "site/modules/$(basename "${f%.md}").html" "../" "../"; done
for f in resources/*.md; do render "$f" "site/resources/$(basename "${f%.md}").html" "../" "../"; done
# the sketches as plain-text pages (so they open in a browser too) + a copy of the .pde folders
cp -r sketches sketches-p5 site/
mkdir -p site/docs && cp -r docs/screenshots site/docs/   # pictures used by overview.html (the README)
# the presenter: copy it in, then bundle every sketch's code into one script (no server needed)
cp -r present/. site/
python3 - <<'PY'
import json, pathlib
pde = {f.parent.name: f.read_text() for f in sorted(pathlib.Path("sketches").glob("*/*.pde"))}
p5 = {f.parent.name: f.read_text() for f in sorted(pathlib.Path("sketches-p5").glob("*/sketch.js"))}
pathlib.Path("site/app/sketches.js").write_text(
    "// Generated by build-site.sh from sketches/ and sketches-p5/. Don't edit by hand.\n"
    "window.SKETCHES = " + json.dumps(pde, indent=0) + ";\n"
    "window.SKETCHES_P5 = " + json.dumps(p5, indent=0) + ";\n")
print(f"Bundled {len(pde)} Processing sketches and {len(p5)} p5.js sketches")
PY
# the lesson plans and resources inside the presenter (#/notes)
python3 -I tools/build-notes.py . site/app/notes-data.js
# rewrite .md links to .html in generated pages
find site -name '*.html' -print0 | xargs -0 sed -i -E 's/href="([^"#:]+)\.md(#[^"]*)?"/href="\1.html\2"/g'
echo "Built: $(pwd)/site/index.html"
