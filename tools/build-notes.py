#!/usr/bin/env python3
"""Bundle the teacher documents (Markdown) into the presenter as site/app/notes.js.

Each document is converted with pandoc to an HTML fragment. Links between documents become
presenter routes (#/notes/<id>), so the notes open inside the app in the same style.

Usage (from build-site.sh): python3 -I tools/build-notes.py <course folder> <output .js>
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

# id, group, source (relative to the course folder). Modules are added in file order.
START = [("overview", "start", "README.md", "Course overview"),
         ("guide", "start", "TEACHER-GUIDE.md", "Teacher guide"),
         ("presenter", "start", "present/README.md", "Using the presenter")]
RESOURCE_ORDER = ["cheatsheet", "error-decoder", "glossary", "coding-train", "book-map"]
# folders that have a page of their own in the presenter
FOLDERS = {"modules": "#/notes", "resources": "#/notes", "sketches": "#/lab", "present": "#/notes/presenter"}


def docs(root):
    out = [{"id": i, "group": g, "src": s, "short": t} for i, g, s, t in START]
    for f in sorted((root / "modules").glob("*.md")):
        out.append({"id": f.stem, "group": "module", "src": f"modules/{f.name}"})
    res = sorted((root / "resources").glob("*.md"),
                 key=lambda f: (RESOURCE_ORDER.index(f.stem) if f.stem in RESOURCE_ORDER else 99, f.stem))
    for f in res:
        out.append({"id": f.stem, "group": "resource", "src": f"resources/{f.name}"})
    return out


def main(root, target):
    items = docs(root)
    by_src = {d["src"]: d["id"] for d in items}

    def fix_link(src, href):
        if re.match(r"^[a-z][a-z0-9+.-]*:", href, re.I):
            return href
        path, _, frag = href.partition("#")
        if not path:
            return f"#/notes/{by_src[src]}/{frag}" if frag else href
        resolved = os.path.normpath(os.path.join(os.path.dirname(src), path))
        if resolved in by_src:
            return f"#/notes/{by_src[resolved]}" + (f"/{frag}" if frag else "")
        if resolved in FOLDERS:
            return FOLDERS[resolved]
        return resolved + ("/" if path.endswith("/") else "")   # a file next to the site (site/ mirrors the course)

    out = []
    for d in items:
        text = (root / d["src"]).read_text(encoding="utf-8")
        title_md = re.search(r"^# (.+)$", text, re.M)
        title = title_md.group(1).strip() if title_md else d["id"]
        if title_md:
            text = text.replace(title_md.group(0), "", 1)   # the page header shows the title
        # screenshots of the presenter (README) don't belong inside the presenter
        text = re.sub(r"<!-- screenshots -->.*?<!-- /screenshots -->\n?", "", text, flags=re.S)
        html = subprocess.run(["pandoc", "-f", "gfm", "-t", "html5", "--syntax-highlighting=none", "--wrap=none"],
                              input=text, capture_output=True, text=True, check=True).stdout
        html = re.sub(r'href="([^"]*)"', lambda m: f'href="{fix_link(d["src"], m.group(1))}"', html)
        item = {"id": d["id"], "group": d["group"], "title": re.sub(r"`([^`]*)`", r"\1", title), "html": html}
        if d.get("short"):
            item["short"] = d["short"]
        out.append(item)

    target.write_text("// Generated by tools/build-notes.py from the course's Markdown files. Don't edit by hand.\n"
                      "window.NOTES = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print(f"Bundled {len(out)} teacher documents")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve())
